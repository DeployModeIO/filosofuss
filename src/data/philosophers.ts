/** Etiquetas localizadas de las eras presentes en el catálogo. */
export const eraLabels: Record<string, Localized> = (() => {
  const map: Record<string, Localized> = {};
  for (const p of philosophers) {
    if (!map[p.era]) map[p.era] = { es: p.era, en: p.eraEn };
  }
  return map;
})();

/** Etiquetas localizadas de las escuelas/movimientos del catálogo. */
export const schoolLabels: Record<string, Localized> = (() => {
  const map: Record<string, Localized> = {};
  for (const p of philosophers) {
    if (!map[p.school]) map[p.school] = { es: p.school, en: p.schoolEn };
  }
  return map;
})();

/** Etiqueta de una era (clave canónica en español) en el idioma activo. */
export function localizeEra(era: string, locale: "es" | "en"): string {
  return eraLabels[era]?.[locale] ?? era;
}

/** Etiqueta de una escuela (clave canónica en español) en el idioma activo. */
export function localizeSchool(school: string, locale: "es" | "en"): string {
  return schoolLabels[school]?.[locale] ?? school;
}

/** Campos visibles de un filósofo ya resueltos al idioma activo. */
export interface PhilosopherDisplay {
  name: string;
  fullName: string;
  era: string;
  school: string;
  nationality: string;
  bio: string;
}

/** Resuelve el metadata visible de un filósofo al idioma solicitado. */
export function localizePhilosopher(
  p: Philosopher,
  locale: "es" | "en",
): PhilosopherDisplay {
  const en = locale === "en";
  return {
    name: en ? p.nameEn : p.name,
    fullName: en ? p.fullNameEn : p.fullName,
    era: localizeEra(p.era, locale),
    school: localizeSchool(p.school, locale),
    nationality: en ? p.nationalityEn : p.nationality,
    bio: en ? p.bioEn : p.bio,
  };
}
